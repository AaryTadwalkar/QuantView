"""
1. What this file does:
   Defines the multi-leg position structures, declared leg containers, and 10-state legging state machine
   for QuantView (Tasks M4-14, M4-16).
   Enables deterministic tracking, mark-to-market valuation, and unwind recovery for complex option structures.

2. Overall design:
   Enforces QUANTVIEW_ENGINE_UI_RESEARCH_SPEC §14, §15, §16, §24 and QUANTVIEW_DATA_SPEC §2.1:
     - LegPosition tracks single contract state (long or short) with exact integer paise fees and marks.
     - PositionGroup coordinates 1-leg, 2-leg, or multi-leg strategy intents with combined P&L and risk thresholds.
     - Implements the canonical 10-state legging lifecycle machine (INTENT_CREATED to GROUP_CLOSED/UNWOUND).
     - Strictly forbids illegal state transitions with InvalidLeggingTransitionError.
     - Propagates stale marks: any single flat or missing leg mark flags the entire group mark as stale.

3. Elements in the file:
   - LegStatus: Lifecycle enumeration for individual leg contracts.
   - LeggingState: Canonical 10-state enumeration of position group execution progress.
   - StrategyIntent: Enumeration of supported strategic multi-leg structures.
   - InvalidLeggingTransitionError: Exception raised on illegal state transitions.
   - LegPosition: Operational container for an individual option leg.
   - PositionGroup: Strategic grouping container coordinating multiple legs and group-level risk.

4. Final output of the file:
   - Exported LegStatus, LeggingState, StrategyIntent, InvalidLeggingTransitionError, LegPosition, and PositionGroup.
"""

from enum import Enum
from typing import Dict, List, Optional, Set

from packages.domain import ContractIdentifier, OrderSide, Paise, UtcEpochSec


class LegStatus(str, Enum):
    """
    1. The use of class:
       Tracks the individual operational status of a single option leg within a position group.

    2. What the class contains:
       - PENDING_OPEN: Order submitted to queue, waiting for next-bar open fill.
       - OPEN: Leg is filled and actively held in portfolio.
       - PENDING_CLOSE: Exit order submitted, waiting for fill.
       - CLOSED: Leg has been successfully closed through normal target/stop/force-flat.
       - UNWOUND: Leg was closed as part of an emergency legging failure recovery.
       - REJECTED: Leg order was rejected by risk, margin, or market conditions.

    3. Technologies used and why:
       String Enum for serializability and integration with ledger events.

    4. Key design and overall design of the class:
       Differentiates normal planned closures from emergency unwind closures for trade auditability.
    """
    PENDING_OPEN = "PENDING_OPEN"
    OPEN = "OPEN"
    PENDING_CLOSE = "PENDING_CLOSE"
    CLOSED = "CLOSED"
    UNWOUND = "UNWOUND"
    REJECTED = "REJECTED"


class LeggingState(str, Enum):
    """
    1. The use of class:
       Canonical 10-state enumeration governing the lifecycle of a multi-leg PositionGroup per ENGINE §24.

    2. What the class contains:
       - INTENT_CREATED: Multi-leg entry signal generated by strategy.
       - LEG_1_QUEUED: First leg entry order queued for next-bar open.
       - LEG_1_FILLED: First leg filled successfully; ready to sequence next leg.
       - LEG_2_QUEUED: Second leg entry order queued for next-bar open.
       - GROUP_OPEN: All declared legs filled; combined position group active.
       - LEG_2_REJECTED: Second leg order rejected; triggers mandatory unwind.
       - UNWIND_QUEUED: Emergency exit order for Leg 1 queued with 3x adverse slippage.
       - UNWOUND: Leg 1 exit filled; group terminated with net loss (terminal).
       - GROUP_CLOSED: All legs exited through target, stop, or force-flat (terminal).
       - HALTED_UNRESOLVED: Execution or unwind could not complete due to missing data or halt (terminal).

    3. Technologies used and why:
       String Enum providing explicit, exhaustive states for deterministic execution.

    4. Key design and overall design of the class:
       Guarantees that partial fills or legging failures cannot masquerade as open spreads.
    """
    INTENT_CREATED = "INTENT_CREATED"
    LEG_1_QUEUED = "LEG_1_QUEUED"
    LEG_1_FILLED = "LEG_1_FILLED"
    LEG_2_QUEUED = "LEG_2_QUEUED"
    GROUP_OPEN = "GROUP_OPEN"
    LEG_2_REJECTED = "LEG_2_REJECTED"
    UNWIND_QUEUED = "UNWIND_QUEUED"
    UNWOUND = "UNWOUND"
    GROUP_CLOSED = "GROUP_CLOSED"
    HALTED_UNRESOLVED = "HALTED_UNRESOLVED"


class StrategyIntent(str, Enum):
    """
    1. The use of class:
       Enumeration of strategic options structures supported by the execution sequencer.

    2. What the class contains:
       - SINGLE_LEG_LONG: Outright long call or put.
       - SINGLE_LEG_SHORT: Outright short call or put (THEORETICAL only in v1).
       - BULL_CALL_SPREAD: Long ATM Call + Short OTM Call (defined debit spread).
       - BEAR_PUT_SPREAD: Long ATM Put + Short OTM Put (defined debit spread).
       - LONG_STRADDLE: Long ATM Call + Long ATM Put (long volatility).
       - SHORT_STRANGLE: Short OTM Call + Short OTM Put (credit structure; THEORETICAL only).
       - LONG_STRANGLE: Long OTM Call + Long OTM Put (long volatility).
       - IRON_CONDOR: 4-leg defined risk structure (representation ready).

    3. Technologies used and why:
       String Enum for strategy classification and execution ordering rules.

    4. Key design and overall design of the class:
       Informs the sequencer whether long hedge legs must precede short risk legs.
    """
    SINGLE_LEG_LONG = "SINGLE_LEG_LONG"
    SINGLE_LEG_SHORT = "SINGLE_LEG_SHORT"
    BULL_CALL_SPREAD = "BULL_CALL_SPREAD"
    BEAR_PUT_SPREAD = "BEAR_PUT_SPREAD"
    LONG_STRADDLE = "LONG_STRADDLE"
    SHORT_STRANGLE = "SHORT_STRANGLE"
    LONG_STRANGLE = "LONG_STRANGLE"
    IRON_CONDOR = "IRON_CONDOR"


class InvalidLeggingTransitionError(Exception):
    """
    1. The use of class:
       Raised when an illegal state transition is attempted on a PositionGroup.

    2. What the class contains:
       - message: Detailed explanation of illegal source and target states.

    3. Technologies used and why:
       Exception subclass ensuring fail-closed engine behavior on protocol violations.

    4. Key design and overall design of the class:
       Prevents silent jumps across lifecycle states (e.g., INTENT_CREATED directly to GROUP_OPEN).
    """
    pass


class LegPosition:
    """
    1. The use of class:
       Tracks individual contract operational and accounting state within a multi-leg PositionGroup.

    2. What the class contains:
       - contract: ContractIdentifier identifying symbol, strike, expiry, and option type.
       - side: OrderSide (BUY for long, SELL for short).
       - qty: Open quantity in integer contract units.
       - entry_price_paise: Quantized fill price at entry in Paise.
       - entry_time: UtcEpochSec when filled.
       - entry_fees_paise: Statutory and broker fees charged at entry.
       - exit_price_paise: Quantized fill price at exit (None while open).
       - exit_time: UtcEpochSec when closed (None while open).
       - exit_fees_paise: Statutory and broker fees charged at exit.
       - current_mark_paise: Latest observed close price in Paise.
       - is_mark_stale: Boolean indicating missing or zero-volume candle.
       - status: LegStatus enum tracking operational phase.

    3. Technologies used and why:
       Plain Python object with integer Paise fields for zero floating-point drift.

    4. Key design and overall design of the class:
       Provides atomic contract accounting and mark-to-market calculations for composite groups.
    """

    def __init__(
        self,
        contract: ContractIdentifier,
        side: OrderSide,
        qty: int,
        entry_price_paise: Paise,
        entry_time: UtcEpochSec,
        entry_fees_paise: Paise = Paise(0),
        status: LegStatus = LegStatus.OPEN,
    ) -> None:
        self.contract = contract
        self.side = side
        self.qty = qty
        self.entry_price_paise = entry_price_paise
        self.entry_time = entry_time
        self.entry_fees_paise = entry_fees_paise
        self.exit_price_paise: Optional[Paise] = None
        self.exit_time: Optional[UtcEpochSec] = None
        self.exit_fees_paise: Paise = Paise(0)
        self.current_mark_paise: Optional[Paise] = None
        self.is_mark_stale: bool = False
        self.status: LegStatus = status

    def mark_unrealized_pnl(self, current_mark_paise: Paise, is_stale: bool = False) -> Paise:
        """
        1. The use of function:
           Updates the leg's valuation mark and calculates its current unrealized mark-to-market P&L.

        2. How does the specific function work:
           - Stores current_mark_paise and stale flag.
           - For long positions (side == BUY): P&L = qty * (current_mark - entry_price).
           - For short positions (side == SELL): P&L = qty * (entry_price - current_mark).
           - Returns unrealized gain/loss as integer Paise.

        3. Concepts used in the function:
           Mark-to-market valuation, exact integer paise arithmetic, directional payoff.

        4. Places where this function is imported and used:
           Used by PositionGroup.calculate_combined_unrealized_pnl and IntrabarFillEngine.

        5. Final output of the function, before and after:
           Before: Previous mark. After: Updated mark and returned unrealized P&L in Paise.
        """
        self.current_mark_paise = current_mark_paise
        self.is_mark_stale = is_stale
        if self.side == OrderSide.BUY:
            price_diff = int(current_mark_paise) - int(self.entry_price_paise)
        else:
            price_diff = int(self.entry_price_paise) - int(current_mark_paise)
        return Paise(self.qty * price_diff)

    def close_leg(
        self,
        exit_price_paise: Paise,
        exit_fees_paise: Paise,
        exit_time: UtcEpochSec,
        is_unwind: bool = False,
    ) -> None:
        """
        1. The use of function:
           Records the terminal closing fill parameters for this leg.

        2. How does the specific function work:
           - Sets exit fill price, fees, and exit timestamp.
           - Sets status to UNWOUND if is_unwind is True, else CLOSED.

        3. Concepts used in the function:
           Position closure lifecycle, unwind provenance.

        4. Places where this function is imported and used:
           Used by PositionGroup and execution engine upon order fill.

        5. Final output of the function, before and after:
           Before: Open leg state. After: Closed/unwound leg state with exit attributes populated.
        """
        self.exit_price_paise = exit_price_paise
        self.exit_fees_paise = exit_fees_paise
        self.exit_time = exit_time
        self.status = LegStatus.UNWOUND if is_unwind else LegStatus.CLOSED

    def gross_realized_pnl(self) -> Paise:
        """
        1. The use of function:
           Calculates gross realized P&L from entry and exit fills in Paise (excluding fees).

        2. How does the specific function work:
           - If exit_price_paise is None (leg not closed), returns Paise(0).
           - For BUY side: qty * (exit_price - entry_price).
           - For SELL side: qty * (entry_price - exit_price).

        3. Concepts used in the function:
           Realized P&L accounting, exact money integer math.

        4. Places where this function is imported and used:
           Used by PositionGroup.calculate_combined_realized_pnl and ledger fill reconciliation.

        5. Final output of the function, before and after:
           Before: Closed leg state. After: Gross realized P&L as integer Paise.
        """
        if self.exit_price_paise is None:
            return Paise(0)
        if self.side == OrderSide.BUY:
            diff = int(self.exit_price_paise) - int(self.entry_price_paise)
        else:
            diff = int(self.entry_price_paise) - int(self.exit_price_paise)
        return Paise(self.qty * diff)

    def net_realized_pnl(self) -> Paise:
        """
        1. The use of function:
           Calculates net realized P&L after deducting round-trip entry and exit fees.

        2. How does the specific function work:
           Subtracts entry_fees_paise and exit_fees_paise from gross_realized_pnl().

        3. Concepts used in the function:
           Net economic gain, statutory fee deduction.

        4. Places where this function is imported and used:
           Used by PositionGroup performance reporting and trade metrics.

        5. Final output of the function, before and after:
           Before: Gross realized P&L. After: Net realized P&L as integer Paise.
        """
        gross = int(self.gross_realized_pnl())
        total_fees = int(self.entry_fees_paise) + int(self.exit_fees_paise)
        return Paise(gross - total_fees)

    def is_open(self) -> bool:
        """
        1. The use of function:
           Checks whether this leg is currently active in the portfolio.

        2. How does the specific function work:
           Returns True if status is OPEN or PENDING_CLOSE.

        3. Concepts used in the function:
           Position liveness detection.

        4. Places where this function is imported and used:
           Used by PositionGroup mark-to-market and exit evaluation routines.

        5. Final output of the function, before and after:
           Before: LegPosition instance. After: Boolean indicating active status.
        """
        return self.status in (LegStatus.OPEN, LegStatus.PENDING_CLOSE)


class PositionGroup:
    """
    1. The use of class:
       Coordinates multi-leg option structures under a single strategic intent per ENGINE §24.

    2. What the class contains:
       - group_id: Unique group identification string.
       - strategy_id: Identifier of the strategy originating the group.
       - intent: StrategyIntent enum (e.g. BULL_CALL_SPREAD).
       - legs: Dictionary mapping contract instrument_key or leg ID to LegPosition.
       - state: LeggingState enum tracking execution machine progress.
       - created_at: UtcEpochSec when intent was created.
       - group_stop_loss_paise: Net combined loss threshold for coordinated exit.
       - group_take_profit_paise: Net combined profit target for coordinated exit.
       - group_trailing_stop_paise: Trailing distance from peak combined P&L.
       - peak_unrealized_pnl_paise: High-water mark of combined unrealized P&L.

    3. Technologies used and why:
       Pure Python state machine with strict transition guards and integer Paise valuations.

    4. Key design and overall design of the class:
       Encapsulates group-level risk bounds, coordinated exit triggers, and unwind recovery semantics.
    """

    # Permitted state transitions per Section 2.3 of Stage 4 plan
    _VALID_TRANSITIONS: Dict[LeggingState, Set[LeggingState]] = {
        LeggingState.INTENT_CREATED: {LeggingState.LEG_1_QUEUED},
        LeggingState.LEG_1_QUEUED: {LeggingState.LEG_1_FILLED, LeggingState.HALTED_UNRESOLVED},
        LeggingState.LEG_1_FILLED: {LeggingState.LEG_2_QUEUED, LeggingState.GROUP_OPEN},
        LeggingState.LEG_2_QUEUED: {LeggingState.GROUP_OPEN, LeggingState.LEG_2_REJECTED},
        LeggingState.GROUP_OPEN: {LeggingState.GROUP_CLOSED, LeggingState.HALTED_UNRESOLVED},
        LeggingState.LEG_2_REJECTED: {LeggingState.UNWIND_QUEUED},
        LeggingState.UNWIND_QUEUED: {LeggingState.UNWOUND, LeggingState.HALTED_UNRESOLVED},
        LeggingState.UNWOUND: set(),
        LeggingState.GROUP_CLOSED: set(),
        LeggingState.HALTED_UNRESOLVED: set(),
    }

    def __init__(
        self,
        group_id: str,
        strategy_id: str,
        intent: StrategyIntent,
        created_at: UtcEpochSec,
        group_stop_loss_paise: Optional[Paise] = None,
        group_take_profit_paise: Optional[Paise] = None,
        group_trailing_stop_paise: Optional[Paise] = None,
        state: LeggingState = LeggingState.INTENT_CREATED,
    ) -> None:
        self.group_id = group_id
        self.strategy_id = strategy_id
        self.intent = intent
        self.created_at = created_at
        self.group_stop_loss_paise = group_stop_loss_paise
        self.group_take_profit_paise = group_take_profit_paise
        self.group_trailing_stop_paise = group_trailing_stop_paise
        self.state = state
        self.legs: Dict[str, LegPosition] = {}
        self.peak_unrealized_pnl_paise: Paise = Paise(0)

    def transition_to(self, new_state: LeggingState) -> None:
        """
        1. The use of function:
           Transitions the PositionGroup to a new legging state after validating transition legality.

        2. How does the specific function work:
           - Checks if new_state is in _VALID_TRANSITIONS for current self.state.
           - If invalid, raises InvalidLeggingTransitionError with diagnostic reason.
           - If valid, updates self.state to new_state.

        3. Concepts used in the function:
           Deterministic finite state machine, fail-closed state protection.

        4. Places where this function is imported and used:
           Used by execution sequencer and fill engines when orders change status.

        5. Final output of the function, before and after:
           Before: Previous LeggingState. After: Validated new LeggingState, or raises error.
        """
        allowed = self._VALID_TRANSITIONS.get(self.state, set())
        if new_state not in allowed:
            raise InvalidLeggingTransitionError(
                f"Invalid legging transition for group {self.group_id}: cannot transition from {self.state.value} to {new_state.value}."
            )
        self.state = new_state

    def add_leg(self, leg_key: str, leg: LegPosition) -> None:
        """
        1. The use of function:
           Registers an individual declared LegPosition under this group.

        2. How does the specific function work:
           Stores the leg instance in self.legs under leg_key.

        3. Concepts used in the function:
           Composite entity composition.

        4. Places where this function is imported and used:
           Used by execution sequencer upon creating or filling leg positions.

        5. Final output of the function, before and after:
           Before: Group without leg. After: Group containing the registered leg.
        """
        self.legs[leg_key] = leg

    def calculate_combined_unrealized_pnl(self) -> Paise:
        """
        1. The use of function:
           Computes the net unrealized mark-to-market P&L across all active open legs.

        2. How does the specific function work:
           - Iterates across all open legs in self.legs.
           - For each open leg with a valid current mark, calculates its unrealized P&L.
           - Sums values in integer Paise.
           - Updates peak_unrealized_pnl_paise if current combined P&L exceeds prior peak.
           - Returns total combined unrealized P&L in Paise.

        3. Concepts used in the function:
           Portfolio aggregation, high-water mark tracking, integer paise math.

        4. Places where this function is imported and used:
           Used by IntrabarFillEngine for group stop-loss, take-profit, and trailing stop evaluation.

        5. Final output of the function, before and after:
           Before: Uncalculated group mark. After: Summed unrealized P&L in Paise and updated peak.
        """
        total = 0
        for leg in self.legs.values():
            if leg.is_open() and leg.current_mark_paise is not None:
                leg_pnl = int(leg.mark_unrealized_pnl(leg.current_mark_paise, leg.is_mark_stale))
                total += leg_pnl

        combined = Paise(total)
        if int(combined) > int(self.peak_unrealized_pnl_paise):
            self.peak_unrealized_pnl_paise = combined
        return combined

    def calculate_combined_realized_pnl(self, gross: bool = False) -> Paise:
        """
        1. The use of function:
           Computes the total realized P&L across all closed or unwound legs in the group.

        2. How does the specific function work:
           - Iterates through legs in self.legs.
           - Sums leg.gross_realized_pnl() if gross is True, else leg.net_realized_pnl().
           - Returns the integer sum as Paise.

        3. Concepts used in the function:
           Multi-leg realized P&L accounting, fee deduction aggregation.

        4. Places where this function is imported and used:
           Used by trade reconciliation and reporting artifacts.

        5. Final output of the function, before and after:
           Before: Individual leg states. After: Total combined realized P&L in Paise.
        """
        total = 0
        for leg in self.legs.values():
            if gross:
                total += int(leg.gross_realized_pnl())
            else:
                total += int(leg.net_realized_pnl())
        return Paise(total)

    def is_group_mark_stale(self) -> bool:
        """
        1. The use of function:
           Determines whether the group's current valuation is stale due to missing or zero-volume data.

        2. How does the specific function work:
           - Examines all open legs.
           - If any open leg is flagged is_mark_stale == True or current_mark_paise is None, returns True.
           - If all open legs have fresh marks, returns False.

        3. Concepts used in the function:
           Stale data propagation invariant (ENGINE §24): a single degraded leg corrupts group mark.

        4. Places where this function is imported and used:
           Used by BacktestRunner and RiskPolicyEvaluator before permitting new group decisions.

        5. Final output of the function, before and after:
           Before: Individual leg stale flags. After: Boolean indicating overall group mark staleness.
        """
        for leg in self.legs.values():
            if leg.is_open():
                if leg.is_mark_stale or leg.current_mark_paise is None:
                    return True
        return False

    def is_terminal(self) -> bool:
        """
        1. The use of function:
           Checks whether the PositionGroup has reached an immutable terminal state.

        2. How does the specific function work:
           Returns True if state is GROUP_CLOSED, UNWOUND, or HALTED_UNRESOLVED.

        3. Concepts used in the function:
           Terminal state detection in finite state automaton.

        4. Places where this function is imported and used:
           Used by execution loops to filter active from inactive position groups.

        5. Final output of the function, before and after:
           Before: PositionGroup instance. After: Boolean indicating terminal status.
        """
        return self.state in (LeggingState.GROUP_CLOSED, LeggingState.UNWOUND, LeggingState.HALTED_UNRESOLVED)

    def update_trailing_stops(self) -> Optional[Paise]:
        """
        1. The use of function:
           Calculates dynamic trailing stop trigger level based on peak unrealized P&L.

        2. How does the specific function work:
           - If group_trailing_stop_paise is configured, computes trigger as:
             peak_unrealized_pnl_paise - group_trailing_stop_paise.
           - Returns computed trigger level in Paise, or None if trailing stop is not enabled.

        3. Concepts used in the function:
           High-water mark trailing stop calculation.

        4. Places where this function is imported and used:
           Used by IntrabarFillEngine during group risk evaluation step.

        5. Final output of the function, before and after:
           Before: Static group thresholds. After: Dynamic trailing stop trigger in Paise or None.
        """
        if self.group_trailing_stop_paise is None:
            return None
        trigger = int(self.peak_unrealized_pnl_paise) - int(self.group_trailing_stop_paise)
        return Paise(trigger)
