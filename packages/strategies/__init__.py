"""
1. What this file does:
   Defines the Strategy(Protocol) contract and signal interfaces for QuantView.

2. Overall design:
   Strategies are decoupled, deterministic state machines. They consume causal feature
   snapshots and emit trading intents. Strategies NEVER import broker SDKs or query raw
   data files directly.

3. Elements in the file:
   - StrategySignal: Intent emitted by strategy (BUY, SELL, HOLD, EXIT).
   - Strategy: Typing Protocol defining the lifecycle methods: on_start, on_bar, on_stop.

4. Final output of the file:
   - Exported strategy protocol and signal definitions.
"""

from enum import Enum
from typing import Dict, Any, Optional, Protocol, runtime_checkable
from packages.domain import UtcEpochSec, ContractIdentifier


class SignalAction(str, Enum):
    """
    1. The use of class:
       Enumerates trading signal actions produced by strategies.

    2. What the class contains:
       - ENTER_LONG: Initiate long position.
       - ENTER_SHORT: Initiate short position (subject to margin guard).
       - EXIT: Liquidate active position.
       - HOLD: Take no action.

    3. Technologies used and why:
       str and Enum for deterministic action comparisons.

    4. Key design and overall design of the class:
       Standard signal taxonomy separating signal generation from order fill execution.
    """
    ENTER_LONG = "ENTER_LONG"
    ENTER_SHORT = "ENTER_SHORT"
    EXIT = "EXIT"
    HOLD = "HOLD"


class StrategySignal:
    """
    1. The use of class:
       Data structure representing a trade signal generated by a Strategy instance.

    2. What the class contains:
       - action: SignalAction enum.
       - timestamp: Causal instant when signal was emitted.
       - target_contract: Optional contract intended for execution.
       - reason: Diagnostic text for audit logs.

    3. Technologies used and why:
       Lightweight class holding immutable signal attributes.

    4. Key design and overall design of the class:
       Enforces causal availability: timestamp must match bar_end of the completed bar.
    """

    def __init__(
        self,
        action: SignalAction,
        timestamp: UtcEpochSec,
        target_contract: Optional[ContractIdentifier] = None,
        reason: str = "",
    ):
        """
        1. The use of function:
           Initializes a StrategySignal instance.

        2. How does the specific function work:
           Stores signal properties.

        3. Concepts used in the function:
           Signal provenance encapsulation.

        4. Places where this function is imported and used:
           Constructed inside Strategy.on_bar() and consumed by simulation/live engine.

        5. Final output of the function, before and after:
           Before: Signal attributes. After: Initialized StrategySignal.
        """
        self.action = action
        self.timestamp = timestamp
        self.target_contract = target_contract
        self.reason = reason


